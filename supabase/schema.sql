create or replace function public.study_board()
returns jsonb language sql stable security definer set search_path = ''
as $$
  select jsonb_build_object(
    'members', coalesce((select jsonb_agg(to_jsonb(m) order by m.id) from public.study_members m), '[]'::jsonb),
    'posts', coalesce((select jsonb_agg(to_jsonb(p) - 'token_hash' order by p.created_at desc) from public.study_posts p), '[]'::jsonb),
    'words', coalesce((select jsonb_agg(to_jsonb(w) order by w.created_at desc) from public.study_words w), '[]'::jsonb),
    'reactions', coalesce((select jsonb_object_agg(r.post_id, r.members) from (
        select post_id, jsonb_agg(member order by created_at) as members from public.study_reactions group by post_id) r), '{}'::jsonb),
    'comments', coalesce((select jsonb_object_agg(c.post_id, c.items) from (
        select post_id, jsonb_agg(jsonb_build_object('id', id, 'member', member, 'text', body, 'at', created_at) order by created_at) as items
        from public.study_comments group by post_id) c), '{}'::jsonb),
    'streaks', coalesce((select jsonb_object_agg(member::text, state) from public.study_streaks), '{}'::jsonb)
  );
$$;

-- 응원: 한 번 누르면 켜지고, 다시 누르면 꺼집니다.
create or replace function public.study_react(post_key uuid, member_no integer)
returns boolean language plpgsql security definer set search_path = ''
as $$
begin
  if not exists (select 1 from public.study_members where id = member_no)
     or not exists (select 1 from public.study_posts where id = post_key) then
    raise exception 'Invalid input';
  end if;
  delete from public.study_reactions where post_id = post_key and member = member_no;
  if found then return false; end if;
  insert into public.study_reactions(post_id, member) values(post_key, member_no);
  return true;
end;
$$;

create or replace function public.study_comment_add(comment_id uuid, post_key uuid, member_no integer, comment_text text)
returns uuid language plpgsql security definer set search_path = ''
as $$
begin
  if not exists (select 1 from public.study_members where id = member_no)
     or not exists (select 1 from public.study_posts where id = post_key)
     or coalesce(length(trim(comment_text)), 0) not between 1 and 500 then
    raise exception 'Invalid input';
  end if;
  insert into public.study_comments(id, post_id, member, body) values(comment_id, post_key, member_no, trim(comment_text))
    on conflict (id) do nothing;
  return comment_id;
end;
$$;

create or replace function public.study_comment_remove(comment_id uuid, member_no integer)
returns boolean language plpgsql security definer set search_path = ''
as $$
begin
  delete from public.study_comments where id = comment_id and member = member_no;
  return found;
end;
$$;

create or replace function public.study_streak_save(member_no integer, new_state jsonb)
returns boolean language plpgsql security definer set search_path = ''
as $$
begin
  if not exists (select 1 from public.study_members where id = member_no)
     or jsonb_typeof(new_state) is distinct from 'object' or length(new_state::text) >= 4000 then
    raise exception 'Invalid input';
  end if;
  insert into public.study_streaks(member, state) values(member_no, new_state)
    on conflict (member) do update set state = excluded.state, updated_at = now();
  return true;
end;
$$;

create or replace function public.study_save(entry jsonb, edit_token text, post_key uuid default null)
returns uuid language plpgsql security definer set search_path = ''
as $$
declare
  post_id_to_save uuid := post_key;
  member_no integer := (entry->>'author')::integer;
  display_name text := case when member_no = 0 then trim(entry->>'author_name') else '' end;
  token_digest text := encode(sha256(convert_to(edit_token, 'UTF8')), 'hex');
  words jsonb := entry->'words';
  post_board text := coalesce(nullif(entry->>'board', ''), 'study');
  word jsonb;
  saved_word uuid;
  keep_words uuid[] := array[]::uuid[];
begin
  if member_no is null or member_no < 0
     or (member_no > 0 and not exists (select 1 from public.study_members where id = member_no))
     or (member_no = 0 and coalesce(length(display_name), 0) not between 1 and 40)
     or post_board not in ('study', 'chat')
     or coalesce(length(edit_token), 0) not between 40 and 128
     or jsonb_typeof(words) is distinct from 'array' or jsonb_array_length(words) > 20 then
    raise exception 'Invalid input';
  end if;

  if post_key is not null then
    update public.study_posts
      set author = member_no, author_name = display_name, title = entry->>'title',
          body = entry->>'body', tag = entry->>'tag', link = entry->>'link'
      where id = post_key and token_hash = token_digest;
    if not found then raise exception 'Invalid edit token'; end if;
  elsif coalesce(entry->>'title', '') <> '' then
    insert into public.study_posts(author, author_name, title, body, tag, link, board, token_hash)
      values(member_no, display_name, entry->>'title', entry->>'body', entry->>'tag', entry->>'link', post_board, token_digest)
      returning id into post_id_to_save;
  elsif jsonb_array_length(words) <> 1 then
    raise exception 'Expected one standalone word';
  end if;

  for word in select value from jsonb_array_elements(words) loop
    if post_id_to_save is not null and coalesce(word->>'id', '') <> '' then
      update public.study_words set author = member_no, author_name = display_name, term = word->>'term',
        meaning = word->>'meaning', example = word->>'example'
        where id = (word->>'id')::uuid and post_id = post_id_to_save
        returning id into saved_word;
      if not found then raise exception 'Word belongs to another post'; end if;
    else
      insert into public.study_words(post_id, author, author_name, term, meaning, example)
        values(post_id_to_save, member_no, display_name, word->>'term', word->>'meaning', word->>'example')
        returning id into saved_word;
    end if;
    keep_words := array_append(keep_words, saved_word);
  end loop;

  if post_id_to_save is not null then
    delete from public.study_words where post_id = post_id_to_save and not (id = any(keep_words));
  end if;
  return post_id_to_save;
end;
$$;

create or replace function public.study_remove(post_key uuid, edit_token text)
returns boolean language plpgsql security definer set search_path = ''
as $$
begin
  delete from public.study_posts
    where id = post_key and token_hash = encode(sha256(convert_to(edit_token, 'UTF8')), 'hex');
  if not found then raise exception 'Invalid edit token'; end if;
  return true;
end;
$$;

